USE ROLE STREAMLIT_USER;
USE WAREHOUSE REPORTING_WH;
USE DATABASE STREAMLIT_APPS;
USE SCHEMA DBO;

CREATE OR REPLACE TABLE STREAMLIT_APPS.DBO.STAIRCASE_BUSINESS_OUTCOMES_MASTER AS
WITH staircase_date_bounds AS (
    SELECT
        MIN(SNAPSHOT_DATE) AS MIN_STAIRCASE_DATE
    FROM ANALYTICS.DBO_BASE_GAINSIGHT.BASE_GAINSIGHT__ACCOUNT_SCORECARD_HISTORICAL_S3
    WHERE STAIRCASEAI_HEALTH IS NOT NULL
       OR STAIRCASEAI_SENTIMENT IS NOT NULL
       OR STAIRCASEAI_ENGAGEMENT IS NOT NULL
),

scorecard AS (
    SELECT
        SFDC_ACCOUNT_ID,
        PARTNER_NAME,
        SNAPSHOT_DATE,
        TRY_CAST(STAIRCASEAI_HEALTH AS NUMBER(18,2)) AS STAIRCASE_HEALTH,
        TRY_CAST(STAIRCASEAI_SENTIMENT AS NUMBER(18,2)) AS STAIRCASE_SENTIMENT,
        TRY_CAST(STAIRCASEAI_ENGAGEMENT AS NUMBER(18,2)) AS STAIRCASE_ENGAGEMENT,
        OVERALL_SCORE_ACCOUNT,
        PARTNER_SENTIMENT,
        PARTNER_ENGAGEMENT,
        CONNECTWISE_ENGAGEMENT,
        CONNECTWISE_EXPERIENCE,
        PARTNER_EXPERIENCE,
        PARTNER_GROWTH,
        NPS,
        CSAT_SUPPORT,
        CSAT_PARTNER_CARE,
        CSAT_PARTNER_SUCCESS,
        CSAT_ACCOUNT_MANAGEMENT,
        TIME_GRANULARITY,
        STATUS_LABEL
    FROM ANALYTICS.DBO_BASE_GAINSIGHT.BASE_GAINSIGHT__ACCOUNT_SCORECARD_HISTORICAL_S3
    WHERE SFDC_ACCOUNT_ID IS NOT NULL
      AND (STAIRCASEAI_HEALTH IS NOT NULL OR STAIRCASEAI_SENTIMENT IS NOT NULL OR STAIRCASEAI_ENGAGEMENT IS NOT NULL)
),

current_staircase AS (
    SELECT
        SFDC_ACCOUNT_ID,
        STAIRCASE_HEALTH_SCORE,
        STAIRCASE_SENTIMENT_SCORE,
        STAIRCASE_ENGAGEMENT_SCORE
    FROM ANALYTICS.DBO_BASE_GAINSIGHT.BASE_GAINSIGHT__COMPANY_S3
    WHERE SFDC_ACCOUNT_ID IS NOT NULL
),

renewals_raw AS (
    SELECT
        r.ACCOUNT_ID,
        r.CONTRACT_ID_UFR,
        r.MASTER_DATE,
        r.RENEWAL_TYPE,
        r.PRODUCT_GROUP_UFR,
        r.PRODUCT_GROUP_RENEW,
        r.PRODUCT_PORTFOLIO_UFR,
        r.COMPANY,
        r.INDUSTRY,
        r.CWS_REGION_C,
        r.CWS_TERRITORY_C,
        r.TOUCH_TIER,
        r.AO,
        r.AO_MANAGER,
        r.RENEWAL_MANAGER,
        r.CWS_PARTNER_HEALTH_SCORE_C,
        r.RISK_SCORE_COLOR,
        r.INITIAL_ATR_C_BUDGET_RATE,
        r.ADJ_ATR_C_BUDGET_RATE,
        r.ALLOCATED_CARR_UFR_C_BUDGET_RATE,
        r.ALLOCATED_CARR_RENEW_C_BUDGET_RATE,
        r.ALLOCATED_CARR_RENEW_GROSS_C_BUDGET_RATE,
        r.CHURN_DOLLARS_C_BUDGET_RATE,
        r.LOST_OR_CHURN_DOLLARS_C_BUDGET_RATE,
        r.NET_PRICE_CHANGE_DOLLARS_C_BUDGET_RATE,
        r.NET_QUANTITY_CHANGE_DOLLARS_C_BUDGET_RATE,
        r.NET_CHANGE_DOLLARS_C_BUDGET_RATE,
        r.PRICE_INC_DOLLARS_C_BUDGET_RATE,
        r.DOWNGRADE_DOLLARS_C_BUDGET_RATE,
        r.CHURN_FLAG,
        CASE
            WHEN r.CHURN_FLAG = 1 THEN 'CHURNED'
            WHEN r.ALLOCATED_CARR_RENEW_GROSS_C_BUDGET_RATE > 0 THEN 'RENEWED'
            ELSE 'PENDING'
        END AS RENEWAL_OUTCOME,
        CASE
            WHEN r.ADJ_ATR_C_BUDGET_RATE > 0
            THEN r.ALLOCATED_CARR_RENEW_GROSS_C_BUDGET_RATE / r.ADJ_ATR_C_BUDGET_RATE
            ELSE NULL
        END AS GROSS_RETENTION_RATE,
        CASE
            WHEN r.ADJ_ATR_C_BUDGET_RATE > 0
            THEN (r.ALLOCATED_CARR_RENEW_GROSS_C_BUDGET_RATE + r.NET_CHANGE_DOLLARS_C_BUDGET_RATE) / r.ADJ_ATR_C_BUDGET_RATE
            ELSE NULL
        END AS NET_RETENTION_RATE
    FROM ANALYTICS.DBO.CARR__RENEWALS_PORTFOLIO_LVL r
    CROSS JOIN staircase_date_bounds b
    WHERE r.INCLUDE_FLAG_C = 1
      AND r.MASTER_DATE >= b.MIN_STAIRCASE_DATE
      AND r.MASTER_DATE <= CURRENT_DATE()
),

renewal_conflicts AS (
    SELECT
        ACCOUNT_ID,
        CONTRACT_ID_UFR,
        MASTER_DATE,
        COUNT(*) AS SOURCE_ROWS_PER_EVENT,
        COUNT(DISTINCT CHURN_FLAG) AS D_CHURN_FLAG,
        COUNT(DISTINCT RENEWAL_OUTCOME) AS D_RENEWAL_OUTCOME,
        COUNT(DISTINCT ALLOCATED_CARR_RENEW_GROSS_C_BUDGET_RATE) AS D_RENEWAL_VALUE,
        COUNT(DISTINCT DOWNGRADE_DOLLARS_C_BUDGET_RATE) AS D_DOWNSELL,
        COUNT(DISTINCT LOST_OR_CHURN_DOLLARS_C_BUDGET_RATE) AS D_PRODUCT_LOSS
    FROM renewals_raw
    GROUP BY 1, 2, 3
),

renewals AS (
    SELECT
        rr.ACCOUNT_ID,
        rr.CONTRACT_ID_UFR,
        rr.MASTER_DATE,
        rr.RENEWAL_TYPE,
        rr.PRODUCT_GROUP_UFR,
        rr.PRODUCT_GROUP_RENEW,
        rr.PRODUCT_PORTFOLIO_UFR,
        rr.COMPANY,
        rr.INDUSTRY,
        rr.CWS_REGION_C,
        rr.CWS_TERRITORY_C,
        rr.TOUCH_TIER,
        rr.AO,
        rr.AO_MANAGER,
        rr.RENEWAL_MANAGER,
        rr.CWS_PARTNER_HEALTH_SCORE_C,
        rr.RISK_SCORE_COLOR,
        rr.INITIAL_ATR_C_BUDGET_RATE,
        rr.ADJ_ATR_C_BUDGET_RATE,
        rr.ALLOCATED_CARR_UFR_C_BUDGET_RATE,
        rr.ALLOCATED_CARR_RENEW_C_BUDGET_RATE,
        rr.ALLOCATED_CARR_RENEW_GROSS_C_BUDGET_RATE,
        rr.CHURN_DOLLARS_C_BUDGET_RATE,
        rr.LOST_OR_CHURN_DOLLARS_C_BUDGET_RATE,
        rr.NET_PRICE_CHANGE_DOLLARS_C_BUDGET_RATE,
        rr.NET_QUANTITY_CHANGE_DOLLARS_C_BUDGET_RATE,
        rr.NET_CHANGE_DOLLARS_C_BUDGET_RATE,
        rr.PRICE_INC_DOLLARS_C_BUDGET_RATE,
        rr.DOWNGRADE_DOLLARS_C_BUDGET_RATE,
        rr.CHURN_FLAG,
        rr.RENEWAL_OUTCOME,
        rr.GROSS_RETENTION_RATE,
        rr.NET_RETENTION_RATE,
        rc.SOURCE_ROWS_PER_EVENT,
        IFF(rc.D_CHURN_FLAG > 1, 1, 0) AS SOURCE_HAS_CHURN_FLAG_CONFLICT,
        IFF(rc.D_RENEWAL_OUTCOME > 1, 1, 0) AS SOURCE_HAS_RENEWAL_OUTCOME_CONFLICT,
        IFF(rc.D_RENEWAL_VALUE > 1, 1, 0) AS SOURCE_HAS_RENEWAL_VALUE_CONFLICT,
        IFF(rc.D_DOWNSELL > 1, 1, 0) AS SOURCE_HAS_DOWNSELL_CONFLICT,
        IFF(rc.D_PRODUCT_LOSS > 1, 1, 0) AS SOURCE_HAS_PRODUCT_LOSS_CONFLICT
    FROM renewals_raw rr
    INNER JOIN renewal_conflicts rc
        ON rr.ACCOUNT_ID = rc.ACCOUNT_ID
       AND rr.CONTRACT_ID_UFR = rc.CONTRACT_ID_UFR
       AND rr.MASTER_DATE = rc.MASTER_DATE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY rr.ACCOUNT_ID, rr.CONTRACT_ID_UFR, rr.MASTER_DATE
        ORDER BY
            IFF(rr.CHURN_FLAG = 1, 1, 0) DESC,
            IFF(rr.ALLOCATED_CARR_RENEW_GROSS_C_BUDGET_RATE IS NOT NULL, 1, 0) DESC,
            ABS(COALESCE(rr.ADJ_ATR_C_BUDGET_RATE, 0)) DESC,
            ABS(COALESCE(rr.ALLOCATED_CARR_RENEW_GROSS_C_BUDGET_RATE, 0)) DESC,
            rr.PRODUCT_PORTFOLIO_UFR,
            rr.PRODUCT_GROUP_UFR,
            rr.RENEWAL_TYPE
    ) = 1
),

arr_trajectory_raw AS (
    SELECT
        a.ACCOUNT_ID,
        a.MONTH_YEAR,
        a.ARR_BUDGET_RATE,
        a.ARR_BUDGET_RATE_DELTA_MOM,
        a.ARR_BUDGET_RATE_DELTA_QOQ,
        a.ARR_BUDGET_RATE_DELTA_YOY,
        a.PARTNER_ARR_CLASSIFICATION_MOM,
        a.PARTNER_ARR_CLASSIFICATION_QOQ,
        a.PARTNER_ARR_CLASSIFICATION_YOY,
        a.PRODUCT_PORTFOLIO,
        a.PRODUCT_GROUP,
        a.PRODUCT_LINE
    FROM ANALYTICS.DBO.CARR__YOY_AGGREGATION a
    CROSS JOIN staircase_date_bounds b
    WHERE a.MONTH_YEAR >= b.MIN_STAIRCASE_DATE
      AND a.MONTH_YEAR <= CURRENT_DATE()
),

arr_trajectory AS (
    SELECT
        ACCOUNT_ID,
        DATE_TRUNC('MONTH', MONTH_YEAR) AS MONTH_YEAR,
        SUM(ARR_BUDGET_RATE) AS ARR_BUDGET_RATE,
        AVG(ARR_BUDGET_RATE_DELTA_MOM) AS ARR_BUDGET_RATE_DELTA_MOM,
        AVG(ARR_BUDGET_RATE_DELTA_QOQ) AS ARR_BUDGET_RATE_DELTA_QOQ,
        AVG(ARR_BUDGET_RATE_DELTA_YOY) AS ARR_BUDGET_RATE_DELTA_YOY,
        CASE
            WHEN COUNT(DISTINCT COALESCE(PARTNER_ARR_CLASSIFICATION_MOM, '__NULL__')) > 1 THEN 'MIXED'
            ELSE MAX(PARTNER_ARR_CLASSIFICATION_MOM)
        END AS PARTNER_ARR_CLASSIFICATION_MOM,
        CASE
            WHEN COUNT(DISTINCT COALESCE(PARTNER_ARR_CLASSIFICATION_QOQ, '__NULL__')) > 1 THEN 'MIXED'
            ELSE MAX(PARTNER_ARR_CLASSIFICATION_QOQ)
        END AS PARTNER_ARR_CLASSIFICATION_QOQ,
        CASE
            WHEN COUNT(DISTINCT COALESCE(PARTNER_ARR_CLASSIFICATION_YOY, '__NULL__')) > 1 THEN 'MIXED'
            ELSE MAX(PARTNER_ARR_CLASSIFICATION_YOY)
        END AS PARTNER_ARR_CLASSIFICATION_YOY,
        CASE
            WHEN COUNT(DISTINCT COALESCE(PRODUCT_PORTFOLIO, '__NULL__')) > 1 THEN 'MIXED'
            ELSE MAX(PRODUCT_PORTFOLIO)
        END AS PRODUCT_PORTFOLIO,
        CASE
            WHEN COUNT(DISTINCT COALESCE(PRODUCT_GROUP, '__NULL__')) > 1 THEN 'MIXED'
            ELSE MAX(PRODUCT_GROUP)
        END AS PRODUCT_GROUP,
        CASE
            WHEN COUNT(DISTINCT COALESCE(PRODUCT_LINE, '__NULL__')) > 1 THEN 'MIXED'
            ELSE MAX(PRODUCT_LINE)
        END AS PRODUCT_LINE,
        COUNT(
            DISTINCT CONCAT_WS(
                '|',
                COALESCE(PRODUCT_PORTFOLIO, '__NULL__'),
                COALESCE(PRODUCT_GROUP, '__NULL__'),
                COALESCE(PRODUCT_LINE, '__NULL__')
            )
        ) AS ARR_PRODUCT_COMBO_COUNT
    FROM arr_trajectory_raw
    GROUP BY 1, 2
)

SELECT
    r.ACCOUNT_ID,
    r.CONTRACT_ID_UFR,
    r.MASTER_DATE,
    r.RENEWAL_TYPE,
    r.PRODUCT_GROUP_UFR,
    r.PRODUCT_GROUP_RENEW,
    r.PRODUCT_PORTFOLIO_UFR,
    r.COMPANY,
    r.INDUSTRY,
    r.CWS_REGION_C,
    r.CWS_TERRITORY_C,
    r.TOUCH_TIER,
    r.AO,
    r.AO_MANAGER,
    r.RENEWAL_MANAGER,
    r.CWS_PARTNER_HEALTH_SCORE_C,
    r.RISK_SCORE_COLOR,
    r.INITIAL_ATR_C_BUDGET_RATE,
    r.ADJ_ATR_C_BUDGET_RATE,
    r.ALLOCATED_CARR_UFR_C_BUDGET_RATE,
    r.ALLOCATED_CARR_RENEW_C_BUDGET_RATE,
    r.ALLOCATED_CARR_RENEW_GROSS_C_BUDGET_RATE,
    r.CHURN_DOLLARS_C_BUDGET_RATE,
    r.LOST_OR_CHURN_DOLLARS_C_BUDGET_RATE,
    r.NET_PRICE_CHANGE_DOLLARS_C_BUDGET_RATE,
    r.NET_QUANTITY_CHANGE_DOLLARS_C_BUDGET_RATE,
    r.NET_CHANGE_DOLLARS_C_BUDGET_RATE,
    r.PRICE_INC_DOLLARS_C_BUDGET_RATE,
    r.DOWNGRADE_DOLLARS_C_BUDGET_RATE,
    r.CHURN_FLAG,
    r.RENEWAL_OUTCOME,
    CASE
        WHEN r.RENEWAL_OUTCOME = 'CHURNED' THEN 1
        WHEN r.RENEWAL_OUTCOME = 'RENEWED' THEN 0
        ELSE NULL
    END AS DERIVED_CHURN_FLAG,
    r.GROSS_RETENTION_RATE,
    r.NET_RETENTION_RATE,
    r.SOURCE_ROWS_PER_EVENT,
    r.SOURCE_HAS_CHURN_FLAG_CONFLICT,
    r.SOURCE_HAS_RENEWAL_OUTCOME_CONFLICT,
    r.SOURCE_HAS_RENEWAL_VALUE_CONFLICT,
    r.SOURCE_HAS_DOWNSELL_CONFLICT,
    r.SOURCE_HAS_PRODUCT_LOSS_CONFLICT,
    s.SNAPSHOT_DATE AS SCORECARD_SNAPSHOT_DATE,
    s.STAIRCASE_HEALTH,
    s.STAIRCASE_SENTIMENT,
    s.STAIRCASE_ENGAGEMENT,
    s.OVERALL_SCORE_ACCOUNT,
    s.PARTNER_SENTIMENT,
    s.PARTNER_ENGAGEMENT,
    s.CONNECTWISE_ENGAGEMENT,
    s.CONNECTWISE_EXPERIENCE,
    s.PARTNER_EXPERIENCE,
    s.PARTNER_GROWTH,
    s.NPS,
    s.CSAT_SUPPORT,
    s.CSAT_PARTNER_CARE,
    s.CSAT_PARTNER_SUCCESS,
    s.CSAT_ACCOUNT_MANAGEMENT,
    s.STATUS_LABEL AS SCORECARD_STATUS,
    c.STAIRCASE_HEALTH_SCORE AS CURRENT_STAIRCASE_HEALTH,
    c.STAIRCASE_SENTIMENT_SCORE AS CURRENT_STAIRCASE_SENTIMENT,
    c.STAIRCASE_ENGAGEMENT_SCORE AS CURRENT_STAIRCASE_ENGAGEMENT,
    arr.MONTH_YEAR AS ARR_MONTH,
    arr.ARR_BUDGET_RATE,
    arr.ARR_BUDGET_RATE_DELTA_MOM,
    arr.ARR_BUDGET_RATE_DELTA_QOQ,
    arr.ARR_BUDGET_RATE_DELTA_YOY,
    arr.PARTNER_ARR_CLASSIFICATION_MOM,
    arr.PARTNER_ARR_CLASSIFICATION_QOQ,
    arr.PARTNER_ARR_CLASSIFICATION_YOY,
    arr.PRODUCT_PORTFOLIO AS ARR_PRODUCT_PORTFOLIO,
    arr.PRODUCT_GROUP AS ARR_PRODUCT_GROUP,
    arr.PRODUCT_LINE AS ARR_PRODUCT_LINE,
    arr.ARR_PRODUCT_COMBO_COUNT,
    IFF(COALESCE(s.STAIRCASE_HEALTH, s.STAIRCASE_SENTIMENT, s.STAIRCASE_ENGAGEMENT) IS NOT NULL, 1, 0) AS HAS_ANY_STAIRCASE_SCORE,
    IFF(
        COALESCE(s.STAIRCASE_HEALTH, s.STAIRCASE_SENTIMENT, s.STAIRCASE_ENGAGEMENT) IS NOT NULL
        AND CASE WHEN r.RENEWAL_OUTCOME IN ('CHURNED', 'RENEWED') THEN 1 ELSE 0 END = 1,
        1,
        0
    ) AS IS_CHURN_ANALYSIS_READY,
    IFF(
        COALESCE(s.STAIRCASE_HEALTH, s.STAIRCASE_SENTIMENT, s.STAIRCASE_ENGAGEMENT) IS NOT NULL
        AND r.ALLOCATED_CARR_RENEW_GROSS_C_BUDGET_RATE IS NOT NULL,
        1,
        0
    ) AS IS_RENEWAL_VALUE_ANALYSIS_READY,
    IFF(
        COALESCE(s.STAIRCASE_HEALTH, s.STAIRCASE_SENTIMENT, s.STAIRCASE_ENGAGEMENT) IS NOT NULL
        AND r.DOWNGRADE_DOLLARS_C_BUDGET_RATE IS NOT NULL,
        1,
        0
    ) AS IS_DOWNSELL_ANALYSIS_READY,
    IFF(
        COALESCE(s.STAIRCASE_HEALTH, s.STAIRCASE_SENTIMENT, s.STAIRCASE_ENGAGEMENT) IS NOT NULL
        AND r.LOST_OR_CHURN_DOLLARS_C_BUDGET_RATE IS NOT NULL,
        1,
        0
    ) AS IS_PRODUCT_LOSS_ANALYSIS_READY
FROM renewals r
LEFT JOIN scorecard s
    ON r.ACCOUNT_ID = s.SFDC_ACCOUNT_ID
    AND s.SNAPSHOT_DATE = (
        SELECT MAX(s2.SNAPSHOT_DATE)
        FROM ANALYTICS.DBO_BASE_GAINSIGHT.BASE_GAINSIGHT__ACCOUNT_SCORECARD_HISTORICAL_S3 s2
        WHERE s2.SFDC_ACCOUNT_ID = r.ACCOUNT_ID
          AND s2.SNAPSHOT_DATE <= r.MASTER_DATE
          AND (s2.STAIRCASEAI_HEALTH IS NOT NULL OR s2.STAIRCASEAI_SENTIMENT IS NOT NULL OR s2.STAIRCASEAI_ENGAGEMENT IS NOT NULL)
    )
LEFT JOIN current_staircase c
    ON r.ACCOUNT_ID = c.SFDC_ACCOUNT_ID
LEFT JOIN arr_trajectory arr
    ON r.ACCOUNT_ID = arr.ACCOUNT_ID
    AND arr.MONTH_YEAR = DATE_TRUNC('MONTH', r.MASTER_DATE);
