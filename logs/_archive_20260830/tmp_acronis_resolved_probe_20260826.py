from TEMPLATES.Python.connection import fetch_dataframe

queries = {
  'zuora_june_ids': '''
    SELECT BILLING_MONTH::DATE AS BILLING_MONTH, SF_ID, SKU_MATCH_GROUP, ZUORA_SKUS, ZUORA_QUANTITY, ZUORA_AMOUNT
    FROM ANALYTICS_DEV.DBT_NFOLD_TRANSFORMATION.ACRONIS_ZUORA_RESOLVED
    WHERE BILLING_MONTH='2026-06-01'::DATE
      AND SF_ID IN ('ACT-00246798','ACT-00238000','ACT-00151761','ACT-00287953','ACT-00239634','ACT-00069994','ACT-00031023','ACT-00150133','ACT-00098437')
    ORDER BY SF_ID, SKU_MATCH_GROUP
  ''',
  'marketplace_june_ids': '''
    SELECT BILLING_MONTH::DATE AS BILLING_MONTH, SF_ID, SKU_MATCH_GROUP, MARKETPLACE_SKUS, MARKETPLACE_QUANTITY, MARKETPLACE_AMOUNT
    FROM ANALYTICS_DEV.DBT_NFOLD_TRANSFORMATION.ACRONIS_MARKETPLACE_RESOLVED
    WHERE BILLING_MONTH='2026-06-01'::DATE
      AND SF_ID IN ('ACT-00246798','ACT-00238000','ACT-00151761','ACT-00287953','ACT-00239634','ACT-00069994','ACT-00031023','ACT-00150133','ACT-00098437')
    ORDER BY SF_ID, SKU_MATCH_GROUP
  ''',
  'cw_billing_raw_june_names': '''
    SELECT BILLING_MONTH::DATE AS BILLING_MONTH, SF_ID, PRODUCT_SKU, SUM(QUANTITY) AS QTY, SUM(EXTENDED_PRICE) AS AMT
    FROM ANALYTICS_DEV.DBT_NFOLD_TRANSFORMATION.THIRD_PARTY_RECON_BILLING_SOURCE
    WHERE VENDOR='Acronis' AND BILLING_MONTH='2026-06-01'::DATE
      AND (
        SF_ID IN ('ACT-00246798','ACT-00238000','ACT-00151761','ACT-00287953','ACT-00239634','ACT-00069994','ACT-00031023','ACT-00150133','ACT-00098437')
      )
    GROUP BY 1,2,3
    ORDER BY SF_ID, PRODUCT_SKU
  ''',
  'billing_by_partner_name_june': '''
    SELECT BILLING_MONTH::DATE AS BILLING_MONTH, PARTNER_NAME, SF_ID, PRODUCT_SKU, SUM(QUANTITY) AS QTY, SUM(EXTENDED_PRICE) AS AMT
    FROM ANALYTICS_DEV.DBT_NFOLD_TRANSFORMATION.THIRD_PARTY_RECON_BILLING_SOURCE
    WHERE VENDOR='Acronis' AND BILLING_MONTH='2026-06-01'::DATE
      AND (
        PARTNER_NAME ILIKE '%Rx Technology%'
        OR PARTNER_NAME ILIKE '%Bulletproof%'
        OR PARTNER_NAME ILIKE '%Serit Ostereng IT%'
        OR PARTNER_NAME ILIKE '%SecureTech%'
        OR PARTNER_NAME ILIKE '%Origami Technology Group%'
        OR PARTNER_NAME ILIKE '%System Go%'
        OR PARTNER_NAME ILIKE '%Flexxa%'
      )
    GROUP BY 1,2,3,4
    ORDER BY PARTNER_NAME, SF_ID, PRODUCT_SKU
  '''
}

for name, sql in queries.items():
    print(f"\n=== {name} ===")
    df = fetch_dataframe(sql)
    print(df.to_string(index=False, max_colwidth=120) if not df.empty else '(no rows)')
