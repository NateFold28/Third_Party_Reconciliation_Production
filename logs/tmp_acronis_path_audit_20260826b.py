from TEMPLATES.Python.connection import fetch_dataframe

queries = {
    'sku_map_spbamsens': '''
        SELECT VENDOR, VENDOR_PRODUCT, VENDOR_SKU, CW_SKU, SKU_MATCH_KEY, MAPPING_NOTES
        FROM ANALYTICS_DEV.DBT_NFOLD_TRANSFORMATION.RECON_SKU_MAP
        WHERE VENDOR='Acronis' AND (VENDOR_PRODUCT='SPBAMSENS' OR SKU_MATCH_KEY='SPBAMSENS' OR CW_SKU ILIKE '%SPBAMSENS%' OR CW_SKU ILIKE '%3PARTYONPREMCLOUDCAP%')
        ORDER BY VENDOR_PRODUCT, CW_SKU
    ''',
    'source_zuora_sharktooth_or_cloudcap': '''
        SELECT BILLING_MONTH::DATE AS BILLING_MONTH, SF_ID, ZUORA_ACCOUNT_NAME, PRODUCT_SKU, QTY, CHARGE_AMOUNT_USD, INVOICE_NUMBER
        FROM ANALYTICS_DEV.DBT_NFOLD_TRANSFORMATION.THIRD_PARTY_RECON_SOURCE_ZUORA_PROD
        WHERE VENDOR='Acronis' AND BILLING_MONTH='2026-06-01'::DATE
          AND (
            ZUORA_ACCOUNT_NAME ILIKE '%SHARKTOOTH%'
            OR ZUORA_ACCOUNT_NAME ILIKE '%Pure Technology /1%'
            OR ZUORA_ACCOUNT_NAME ILIKE '%The Learning Exchange%'
            OR ZUORA_ACCOUNT_NAME ILIKE '%Virtual Communication Specialists%'
            OR PRODUCT_SKU ILIKE '%3PARTYONPREMCLOUDCAP%'
            OR PRODUCT_SKU ILIKE '%SPBAMSENS%'
          )
        ORDER BY ZUORA_ACCOUNT_NAME, SF_ID, PRODUCT_SKU
    ''',
    'source_zuora_cloudcap_sfids': '''
        SELECT BILLING_MONTH::DATE AS BILLING_MONTH, SF_ID, ZUORA_ACCOUNT_NAME, PRODUCT_SKU, SUM(QTY) AS QTY, SUM(CHARGE_AMOUNT_USD) AS AMT
        FROM ANALYTICS_DEV.DBT_NFOLD_TRANSFORMATION.THIRD_PARTY_RECON_SOURCE_ZUORA_PROD
        WHERE VENDOR='Acronis' AND BILLING_MONTH='2026-06-01'::DATE
          AND PRODUCT_SKU ILIKE '%3PARTYONPREMCLOUDCAP%'
        GROUP BY 1,2,3,4
        ORDER BY AMT DESC
        LIMIT 80
    ''',
    'billing_matched_sharktooth': '''
        SELECT BILLING_MONTH::DATE AS BILLING_MONTH, SF_ID, CW_ACCOUNT_NAME, PRODUCT_SKU, ZUORA_QUANTITY, ZUORA_CHARGE_AMOUNT
        FROM ANALYTICS_DEV.DBT_NFOLD_TRANSFORMATION.ACRONIS_BILLING_MATCHED
        WHERE BILLING_MONTH='2026-06-01'::DATE
          AND (CW_ACCOUNT_NAME ILIKE '%SHARKTOOTH%' OR SF_ID='ACT-00153605')
        ORDER BY CW_ACCOUNT_NAME, PRODUCT_SKU
    ''',
    'combined_seed_sharktooth': '''
        SELECT BILLING_MONTH::DATE AS BILLING_MONTH, TENANT_NAME, SF_ID, CMS_ID, BILLING_TYPE, VENDOR_SKU, CW_SKU
        FROM ANALYTICS_DEV.DBT_NFOLD_TRANSFORMATION.ACRONIS_COMBINED_MAPPING_SEED
        WHERE BILLING_MONTH='2026-06-01'::DATE
          AND (TENANT_NAME ILIKE '%SHARKTOOTH%' OR SF_ID='ACT-00153605')
        ORDER BY TENANT_NAME, VENDOR_SKU, CW_SKU
    '''
}

for n,q in queries.items():
    print(f"\n=== {n} ===")
    df = fetch_dataframe(q)
